from pathlib import Path

# --- The protocol, as data -------------------------------------------------

STATES = ("Draft", "Accepted", "Amended", "Deprecated", "Superseded")
LIVE_STATES = ("Draft", "Accepted", "Amended")
HISTORICAL_STATES = ("Deprecated", "Superseded")
NEEDS_BY = ("Amended", "Deprecated", "Superseded")

REQUIRED_HEADINGS = (
    "## Context",
    "## Decision",
    "## Consequences",
    "## Alternatives Considered",
    "## References",
)
# A subsection of "## Alternatives Considered", not a section of its own: the
# canonical-heading check encodes that nesting, so this must stay ###.
DO_NOTHING_HEADING = "### Do Nothing"
PROMOTION_HEADING = "## Promotion"

# --strict promotes these warning kinds to errors. It deliberately does not
# touch `legacy` (bodies the protocol forbids rewriting, so the warning is
# permanent by design) or `judgement` (a heuristic a human has to settle).
STRICT_PROMOTES = ("lint", "unmanaged")

REQUIRED_FIELDS = ("id", "title", "summary", "date", "authors", "reviewers", "status")
SUMMARY_MAX = 140
INDEX_NAME = "README.md"
INDEX_MARKER = "<!-- generated by drs; do not edit below -->"

ID_RE = re.compile(r"^DR-(\d{4,})$")
SLUG_RE = re.compile(r"^(\d{4,})-([a-z0-9]+(?:-[a-z0-9]+)*)$")

DEFAULT_PREAMBLE = """# Decision records

One record per decision that binds future work: what the situation was,
what was decided, what it cost, what was rejected and why. The protocol is
the `decisions` skill; the index below is generated from the records' front
matter by `drs.py index` and checked by `drs.py check`.
"""


class DrsError(Exception):
    """A failure that should stop the command, with a message for the user."""

    pass


class FrontMatterError(DrsError):
    pass


# --- Front matter: a deliberately small dialect ----------------------------


def _unescape(raw: str, where: str) -> str:
    out, i = [], 0
    while i < len(raw):
        ch = raw[i]
        if ch == "\\" and i + 1 < len(raw):
            nxt = raw[i + 1]
            if nxt not in ('"', "\\"):
                raise FrontMatterError(
                    f"{where}: unsupported escape \\{nxt}; the dialect allows only "
                    '\\" and \\\\'
                )
            out.append(nxt)
            i += 2
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def _split_flow(body: str, where: str) -> list[str]:
    """Split the inside of a flow sequence on commas that are not quoted.

    A flow sequence is the one-line `["a", "b"]` list form the dialect allows
    for `authors`, `reviewers`, `supersedes` and `legacy_bodies`. The whole
    difficulty is that a comma or quote inside a value is not a separator, so
    this walks the body one character at a time tracking three states:

        in_quote      inside "..." or '...'; separators are ignored
        escaped       the previous character was a backslash, so the current
                      one is literal even if it is the closing quote

    Getting the `escaped` state wrong is how a value like "A \"quoted, person\""
    gets split at its internal comma, which produces front matter the rest of
    this file then refuses to parse.
    """
    items, buf = [], []
    quote = None
    escaped = False
    for ch in body:
        if escaped:
            # The character after a backslash is data, never a delimiter.
            buf.append(ch)
            escaped = False
            continue
        if ch == "\\" and quote == '"':
            buf.append(ch)
            escaped = True
            continue
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in ('"', "'"):
            quote = ch
            buf.append(ch)
            continue
        if ch == ",":
            items.append("".join(buf))
            buf = []
            continue
        buf.append(ch)
    if quote:
        raise FrontMatterError(f"{where}: unterminated quoted string")
    if "".join(buf).strip():
        items.append("".join(buf))
    return [item.strip() for item in items]


def parse_scalar(raw: str, where: str):
    """Turn one right-hand side into a str or a list of str.

    Accepts exactly what the dialect allows: a quoted string, a bare scalar, or
    a one-line flow sequence of those. Everything YAML offers beyond that —
    anchors, tags, block scalars, inline mappings — is rejected with the line,
    because a format a tool can check is worth more than one that accepts
    everything.
    """
    raw = raw.strip()
    if not raw:
        raise FrontMatterError(f"{where}: missing value")
    if raw[0] == '"':
        if len(raw) < 2 or not raw.endswith('"'):
            raise FrontMatterError(f"{where}: unterminated double-quoted string")
        return _unescape(raw[1:-1], where)
    if raw[0] == "'":
        if len(raw) < 2 or not raw.endswith("'"):
            raise FrontMatterError(f"{where}: unterminated single-quoted string")
        return raw[1:-1]
    if raw[0] == "[":
        if not raw.endswith("]"):
            raise FrontMatterError(f"{where}: unterminated flow sequence")
        return [parse_scalar(item, where) for item in _split_flow(raw[1:-1], where)]
    if raw[0] == "{":
        raise FrontMatterError(
            f"{where}: inline mappings are outside the dialect; use a block mapping"
        )
    if raw[0] in "&*!|>%@`":
        raise FrontMatterError(
            f"{where}: {raw[0]!r} starts a construct outside the dialect "
            "(anchors, tags, block scalars); quote the value or put it in the body"
        )
    return raw


def parse_front_matter(lines: list[str], path: Path) -> dict:
    """Parse the restricted dialect: scalars, one nested mapping, flow lists.

    >>> parse_front_matter(['id: "DR-0001"', "status:", '  state: "Draft"'], Path("x.md"))
    {'id': 'DR-0001', 'status': {'state': 'Draft'}}

    `lines` excludes the fences; `path` is used only to build error locations.
    """
    data: dict = {}
    nested_key = None
    for offset, line in enumerate(lines):
        where = f"{path}:{offset + 2}"
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        indented = line[0] in " \t"
        if indented:
            if nested_key is None:
                raise FrontMatterError(
                    f"{where}: indented line outside a mapping; only a value of "
                    "`status` may be a block"
                )
            key, sep, raw = line.strip().partition(":")
            if not sep or not key.strip():
                raise FrontMatterError(f"{where}: expected `key: value`")
            key = key.strip()
            if key in data[nested_key]:
                raise FrontMatterError(f"{where}: duplicate key {key!r} in {nested_key}")
            data[nested_key][key] = parse_scalar(raw, where)
            continue
        key, sep, raw = line.partition(":")
        if not sep:
            raise FrontMatterError(f"{where}: expected `key: value`")
        key = key.strip()
        if not key:
            raise FrontMatterError(f"{where}: empty key")
        if key in data:
            raise FrontMatterError(f"{where}: duplicate key {key!r}")
        if not raw.strip():
            if key != "status":
                raise FrontMatterError(
                    f"{where}: {key!r} needs a value; only `status` may be a mapping"
                )
            data[key] = {}
            nested_key = key
            continue
        data[key] = parse_scalar(raw, where)
        nested_key = None
    return data


def split_document(text: str, path: Path) -> tuple[list[str] | None, str]:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], "\n".join(lines[i + 1 :])
    raise FrontMatterError(f"{path}: front matter opened on line 1 and never closed")


# --- Records ---------------------------------------------------------------


@dataclass
class Record:
    path: Path
    rel: Path  # relative to the records directory
    front: dict
    body: str

    # Every accessor below returns the field's type or an empty one. A record
    # with `id: ["DR-0001"]` is malformed, and the validator says so; nothing
    # downstream may crash on it or quietly stringify it. Raw access is
    # deliberate: `front` stays as parsed, so the validator can report the
    # actual value it found.

    def scalar(self, key: str) -> str:
        """A string field, or "" when absent or not a string."""
        value = self.front.get(key)
        return value if isinstance(value, str) else ""

    def sequence(self, key: str) -> list[str]:
        """A flow sequence of strings, or [] when absent or malformed."""
        value = self.front.get(key)
        if isinstance(value, list) and all(isinstance(item, str) for item in value):
            return list(value)
        return []

    @property
    def id(self) -> str:
        return self.scalar("id")

    @property
    def title(self) -> str:
        return self.scalar("title")

    @property
    def summary(self) -> str:
        return self.scalar("summary")

    @property
    def date(self) -> str:
        return self.scalar("date")

    @property
    def authors(self) -> list[str]:
        return self.sequence("authors")

    @property
    def reviewers(self) -> list[str]:
        return self.sequence("reviewers")

    @property
    def status(self) -> dict:
        """The status mapping, or {} when it is not a mapping of strings."""
        status = self.front.get("status")
        if not isinstance(status, dict):
            return {}
        if not all(isinstance(key, str) and isinstance(value, str) for key, value in status.items()):
            return {}
        return dict(status)

    @property
    def state(self) -> str:
        return self.status.get("state", "")

    @property
    def by(self) -> str | None:
        return self.status.get("by")

    @property
    def supersedes(self) -> list[str]:
        return self.sequence("supersedes")

    @property
    def legacy_bodies(self) -> list[str]:
        return self.sequence("legacy_bodies")

    @property
    def headings(self) -> set[str]:
        """Canonical heading lines, exactly as written, outside code fences.

        Two rules, both from the protocol: the comparison is whole-line and
        literal, so an indented `  ## Context` is not `## Context`; and fenced
        blocks are skipped, so a record whose only `## Decision` is inside a
        ```markdown example does not satisfy the requirement.
        """
        headings: set[str] = set()
        fenced = False
        for line in self.body.splitlines():
            stripped = line.strip()
            if stripped.startswith("```") or stripped.startswith("~~~"):
                fenced = not fenced
                continue
            if fenced:
                continue
            if line.startswith("#"):
                headings.add(line)
        return headings


@dataclass
class Finding:
    """One audit result.

    `kind` exists because --strict is a policy about categories, not about
    severity: it promotes `unmanaged` and `lint` findings to errors and leaves
    `legacy` (bodies the protocol forbids rewriting) and `judgement` (heuristics
    a human has to settle) as warnings forever.
    """

    level: str  # "error" | "warning"
    where: str
    message: str
    kind: str = "protocol"  # protocol | lint | unmanaged | legacy | judgement


@dataclass
class Corpus:
    directory: Path
    records: list[Record] = field(default_factory=list)
    findings: list[Finding] = field(default_factory=list)

    def by_id(self, issue_id: str) -> Record | None:
        for record in self.records:
            if record.id == issue_id:
                return record
        return None

    def legacy_ids(self) -> set[str]:
        """Ids exempted by any record carrying legacy_bodies."""
        exempt: set[str] = set()
        for record in self.records:
            exempt.update(str(item) for item in record.legacy_bodies)
        return exempt


def discover(directory: Path) -> list[Path]:
    """Every .md under the directory, recursively, minus the generated index."""
    if not directory.is_dir():
        raise DrsError(f"{directory} is not a directory; pass --dir or create it")
    paths = []
    for path in sorted(directory.rglob("*.md")):
        if path == directory / INDEX_NAME:
            continue
        if any(part.startswith(".") for part in path.relative_to(directory).parts):
            continue
        paths.append(path)
    return paths


def load(directory: Path) -> Corpus:
    """Read every record under `directory` into a Corpus.

    Two things do not become records, and both are deliberate:

    - the generated index, because it is a view of the records rather than one;
    - any `.md` with no front matter, which is reported as *unmanaged* instead.
      Forward-only adoption leaves such files alone, so they are a warning by
      default and an error under --strict, but they are not failed silently and
      not guessed at.

    A file that fails to parse becomes an error finding, not an exception: one
    broken record should not stop the audit of the other twenty.
    """
    corpus = Corpus(directory=directory)
    for path in discover(directory):
        rel = path.relative_to(directory)
        text = path.read_text(encoding="utf-8")
        try:
            front_lines, body = split_document(text, path)
        except FrontMatterError as exc:
            corpus.findings.append(Finding("error", str(rel), str(exc)))
            continue
        if front_lines is None:
            corpus.findings.append(
                Finding(
                    "warning",
                    str(rel),
                    "no front matter: unmanaged file (an error under --strict)",
                    kind="unmanaged",
                )
            )
            continue
        try:
            front = parse_front_matter(front_lines, path)
        except FrontMatterError as exc:
            corpus.findings.append(Finding("error", str(rel), str(exc)))
            continue
        corpus.records.append(Record(path=path, rel=rel, front=front, body=body))
    return corpus


# --- Validation ------------------------------------------------------------


def canonicalize_id(number: int) -> str:
    """Spell a record number as an id: DR- plus four digits, widening if needed.

    The generation-side twin of ID_RE, which only matches. Renaming a record
    number into its id and matching an existing id are different jobs, and the
    two living in the same section read as duplicates.
    """
    return f"DR-{number:0{max(4, len(str(number)))}d}"


SCALAR_FIELDS = ("id", "title", "summary", "date")
SEQUENCE_FIELDS = ("authors", "reviewers", "supersedes", "legacy_bodies")


def check_record(record: Record, corpus: Corpus) -> list[Finding]:
    """Validate one record's fields, shape and links.

    Types come first, because every later check reads a field: a record whose
    `id` is a sequence is reported as malformed and then skipped, rather than
    crashing the comparison that follows.
    """
    out: list[Finding] = []
    where = str(record.rel)
    legacy = record.id in corpus.legacy_ids()
    front = record.front

    for name in REQUIRED_FIELDS:
        if name not in front:
            out.append(Finding("error", where, f"missing required field {name!r}"))

    for name in SCALAR_FIELDS:
        if name in front and not isinstance(front[name], str):
            out.append(
                Finding(
                    "error",
                    where,
                    f"{name!r} must be a scalar, not {type(front[name]).__name__}",
                )
            )
    for name in SEQUENCE_FIELDS:
        if name in front and not (
            isinstance(front[name], list) and all(isinstance(item, str) for item in front[name])
        ):
            out.append(
                Finding(
                    "error",
                    where,
                    f"{name!r} must be a flow sequence of scalars, not {type(front[name]).__name__}",
                )
            )
    if "status" in front and not isinstance(front["status"], dict):
        out.append(Finding("error", where, "status must be a block mapping"))
    elif "status" in front and not all(
        isinstance(value, str) for value in front["status"].values()
    ):
        out.append(Finding("error", where, "status values must be scalars"))

    match = ID_RE.match(record.id)
    if "id" not in front:
        pass  # already reported as a missing field
    elif not isinstance(front["id"], str):
        pass  # already reported as a type error
    elif not record.id.strip():
        out.append(Finding("error", where, "id is empty; a record needs its handle"))
    elif not match:
        out.append(Finding("error", where, f"id {record.id!r} is not DR-<4+ digits>"))
    else:
        number = int(match.group(1))
        canonical = canonicalize_id(number)
        if canonical != record.id:
            out.append(
                Finding(
                    "error",
                    where,
                    f"id {record.id!r} is not zero-padded to its width; expected {canonical!r}",
                )
            )

    if "title" in front and isinstance(front["title"], str) and not record.title.strip():
        out.append(Finding("error", where, "title is empty"))
    if "summary" in front and isinstance(front["summary"], str):
        if not record.summary.strip():
            out.append(Finding("error", where, "summary is empty; it is the index line"))
        elif len(record.summary) > SUMMARY_MAX:
            out.append(
                Finding(
                    "error",
                    where,
                    f"summary is {len(record.summary)} characters; limit {SUMMARY_MAX}",
                )
            )
    for name, value in (("title", record.title), ("summary", record.summary)):
        if value and value != value.strip():
            out.append(
                Finding(
                    "error",
                    where,
                    f"{name!r} has leading or trailing whitespace; the index is a "
                    "table and cannot carry it — trim the value",
                )
            )

    if record.date:
        try:
            datetime.date.fromisoformat(record.date)
        except ValueError:
            out.append(Finding("error", where, f"date {record.date!r} is not YYYY-MM-DD"))
    elif "date" in front and isinstance(front["date"], str):
        out.append(Finding("error", where, "date is empty"))

    if "authors" in front and isinstance(front["authors"], list):
        if not record.authors:
            out.append(Finding("error", where, "authors is empty; name who reasoned it out"))
    if "reviewers" in front and isinstance(front["reviewers"], list):
        if not record.reviewers and record.state != "Draft":
            out.append(
                Finding(
                    "error",
                    where,
                    f"{record.state} record has no reviewers; a record nobody ratified is a Draft",
                )
            )

    state = record.state
    if state not in STATES:
        out.append(
            Finding("error", where, f"status.state {state!r} is not one of {', '.join(STATES)}")
        )
    needs_by = state in NEEDS_BY
    if needs_by and not record.by:
        out.append(Finding("error", where, f"{state} record needs status.by naming its cause"))
    elif not needs_by and record.by:
        # Junk metadata rather than a wrong decision: nothing reads it, nothing
        # is misrepresented. Tolerated by default, fatal under --strict.
        out.append(
            Finding(
                "warning",
                where,
                f"status.by is set on a record in state {state}, where it means nothing",
                kind="lint",
            )
        )

    if "date" in record.status:
        try:
            datetime.date.fromisoformat(record.status["date"])
        except ValueError:
            out.append(
                Finding("error", where, f"status.date {record.status['date']!r} is not YYYY-MM-DD")
            )

    headings = record.headings
    for heading in (*REQUIRED_HEADINGS, DO_NOTHING_HEADING):
        if heading in headings:
            continue
        if legacy:
            out.append(
                Finding(
                    "warning",
                    where,
                    f"missing heading {heading!r} (legacy_bodies)",
                    kind="legacy",
                )
            )
        else:
            out.append(Finding("error", where, f"missing heading {heading!r}"))
    if state == "Draft" and PROMOTION_HEADING not in headings:
        if legacy:
            out.append(
                Finding(
                    "warning",
                    where,
                    f"missing heading {PROMOTION_HEADING!r} (legacy_bodies)",
                    kind="legacy",
                )
            )
        else:
            out.append(Finding("error", where, f"Draft record needs {PROMOTION_HEADING!r}"))

    slug = SLUG_RE.match(record.rel.stem)
    expected = "NNNN-slug.md with a lowercase hyphenated slug"
    if not slug:
        out.append(
            Finding(
                "warning",
                where,
                f"filename is not {expected} (legacy_bodies)",
                kind="legacy",
            )
            if legacy
            else Finding("error", where, f"filename is not {expected}")
        )
    elif record.id and match and slug.group(1) != match.group(1):
        message = f"filename numbers {slug.group(1)} but id is {record.id}"
        out.append(
            Finding("warning", where, message + " (legacy_bodies)", kind="legacy")
            if legacy
            else Finding("error", where, message)
        )

    for target in _relative_links(record.body):
        if not (record.path.parent / target).exists():
            out.append(Finding("error", where, f"relative link does not resolve: {target}"))
    return out


def _relative_links(body: str) -> list[str]:
    """Markdown link targets that point inside the repository."""
    targets = []
    for match in re.finditer(r"\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)", body):
        target = match.group(1)
        if "://" in target or target.startswith(("#", "/", "mailto:")):
            continue
        target = target.split("#", 1)[0]
        if target:
            targets.append(target)
    return targets


def check_graph(corpus: Corpus) -> list[Finding]:
    out: list[Finding] = []
    ids = {}
    numbers = {}
    for record in corpus.records:
        match = ID_RE.match(record.id)
        if not record.id or not match:
            continue
        number = int(match.group(1))
        if number in numbers:
            out.append(
                Finding(
                    "error",
                    str(record.rel),
                    f"{record.id} is the same record number as {numbers[number].id} "
                    f"({numbers[number].rel}); ids are single spellings of a number",
                )
            )
        else:
            numbers[number] = record
        if record.id in ids:
            out.append(
                Finding(
                    "error",
                    str(record.rel),
                    f"id {record.id} is also used by {ids[record.id]}",
                )
            )
        else:
            ids[record.id] = str(record.rel)

    for record in corpus.records:
        where = str(record.rel)
        if record.by and record.by not in ids:
            out.append(Finding("error", where, f"status.by {record.by} does not resolve"))
        if record.id and record.by == record.id:
            out.append(
                Finding("error", where, "status.by names this record; it cannot be its own cause")
            )
        if record.id and record.id in record.supersedes:
            out.append(
                Finding("error", where, "supersedes lists this record; it cannot replace itself")
            )
        for target_id in record.supersedes:
            target = corpus.by_id(str(target_id))
            if target is None:
                out.append(Finding("error", where, f"supersedes {target_id} does not resolve"))
                continue
            if target.state != "Superseded":
                out.append(
                    Finding(
                        "error",
                        where,
                        f"supersedes {target_id} but that record is {target.state or 'unset'}, "
                        "not Superseded",
                    )
                )
            if target.by != record.id:
                out.append(
                    Finding(
                        "error",
                        where,
                        f"supersedes {target_id} but {target_id}.status.by is {target.by!r}, "
                        f"expected {record.id!r}",
                    )
                )
        if record.state == "Superseded":
            if not record.by:
                continue  # already reported by the needs_by rule
            superseding = corpus.by_id(record.by)
            if superseding is not None and record.id not in superseding.supersedes:
                out.append(
                    Finding(
                        "error",
                        where,
                        f"Superseded by {record.by}, which does not list {record.id} in supersedes",
                    )
                )

    for record in corpus.records:
        if not record.legacy_bodies:
            continue
        if record.id and record.id in [str(item) for item in record.legacy_bodies]:
            out.append(
                Finding(
                    "error",
                    str(record.rel),
                    "legacy_bodies lists this record itself; only an adopting record "
                    "may exempt others",
                )
            )
        for listed in record.legacy_bodies:
            target = corpus.by_id(str(listed))
            if target is None:
                out.append(
                    Finding(
                        "error",
                        str(record.rel),
                        f"legacy_bodies lists {listed}, which is not a managed record",
                    )
                )
            elif not _needs_legacy_exemption(target):
                out.append(
                    Finding(
                        "warning",
                        str(record.rel),
                        f"legacy_bodies lists {listed}, whose body already conforms; prune it",
                        kind="lint",
                    )
                )

    out.extend(_cycle_findings(corpus, ids))
    out.extend(_duplicate_titles(corpus))
    return out


def _cycle_findings(corpus: Corpus, ids: dict[str, str]) -> list[Finding]:
    """Reject supersession and cause cycles.

    `supersedes` and `status.by` are opposite directions of the same relation —
    a correct pair is `new.supersedes = [old]` with `old.status.by = new` — so
    they are walked separately. Merging them into one graph would report every
    correct supersession as a cycle.
    """
    # Self-edges are excluded because they already have their own, more
    # specific finding; reporting a one-node "cycle" on top of it is noise.
    supersession = {
        record.id: [
            target for target in record.supersedes if target in ids and target != record.id
        ]
        for record in corpus.records
        if record.id
    }
    cause = {
        record.id: [record.by] if record.by in ids and record.by != record.id else []
        for record in corpus.records
        if record.id
    }
    out: list[Finding] = []
    for label, graph in (("supersedes", supersession), ("status.by", cause)):
        cycle = _find_cycle(graph)
        if cycle:
            out.append(
                Finding(
                    "error",
                    ids[cycle[0]],
                    f"{label} cycle: {' -> '.join(cycle)}",
                )
            )
    return out


def _find_cycle(graph: dict[str, list[str]]) -> list[str] | None:
    """Depth-first walk returning one cycle as a path, or None if acyclic."""
    UNVISITED, OPEN, DONE = 0, 1, 2
    state = {node: UNVISITED for node in graph}
    stack: list[str] = []
    for start in graph:
        if state[start] != UNVISITED:
            continue
        # Iterative so a long chain cannot exhaust the interpreter's stack.
        work: list[tuple[str, bool]] = [(start, False)]
        while work:
            node, leaving = work.pop()
            if leaving:
                state[node] = DONE
                if stack and stack[-1] == node:
                    stack.pop()
                continue
            if state[node] == DONE:
                continue
            state[node] = OPEN
            stack.append(node)
            work.append((node, True))
            for neighbour in graph.get(node, []):
                if state[neighbour] == OPEN:
                    start_of_cycle = stack.index(neighbour)
                    return stack[start_of_cycle:] + [neighbour]
                if state[neighbour] == UNVISITED:
                    work.append((neighbour, False))
    return None


def _needs_legacy_exemption(record: Record) -> bool:
    headings = record.headings
    if any(heading not in headings for heading in REQUIRED_HEADINGS):
        return True
    if DO_NOTHING_HEADING not in headings:
        return True
    if record.state == "Draft" and PROMOTION_HEADING not in headings:
        return True
    slug = SLUG_RE.match(record.rel.stem)
    if slug is None:
        return True
    match = ID_RE.match(record.id)
    return bool(match) and slug.group(1) != match.group(1)


def _duplicate_titles(corpus: Corpus) -> list[Finding]:
    def tokens(title: str) -> set[str]:
        return set(re.findall(r"[a-z0-9]+", title.lower()))

    live = [r for r in corpus.records if r.state in LIVE_STATES and r.title]
    out: list[Finding] = []
    for i, first in enumerate(live):
        for second in live[i + 1 :]:
            a, b = tokens(first.title), tokens(second.title)
            if not a or not b:
                continue
            score = len(a & b) / len(a | b)
            if score >= 0.6:
                out.append(
                    Finding(
                        "warning",
                        str(second.rel),
                        f"title resembles {first.id} ({first.title!r}, {score:.0%} overlap); "
                        "has this already been decided?",
                        kind="judgement",
                    )
                )
    return out


# --- The index -------------------------------------------------------------


def _sort_key(record: Record):
    match = ID_RE.match(record.id)
    return (int(match.group(1)) if match else 0, str(record.rel))


def _row(record: Record, with_state: bool = True) -> str:
    # A pipe in a path would split the cell. Legacy filenames are exempt from
    # the slug grammar, so this is reachable; `_cells` already unescapes it.
    target = record.rel.as_posix().replace("|", "\\|")
    link = f"[{record.id or '?'}]({target})"
    title = str(record.title).replace("|", "\\|")
    summary = str(record.summary).replace("|", "\\|")
    cells = [link, title, summary]
    if with_state:
        cells.append(record.state)
    return "| " + " | ".join(cells) + " |"


def _table(records: list[Record], with_state: bool = True) -> list[str]:
    header = "| Record | Title | Decision |" + (" State |" if with_state else "")
    rule = "| --- | --- | --- |" + (" --- |" if with_state else "")
    rows = [_row(record, with_state) for record in sorted(records, key=_sort_key)]
    return [header, rule, *rows]


def render_index(corpus: Corpus, preamble: str) -> str:
    live = [r for r in corpus.records if r.state in LIVE_STATES]
    historical = [r for r in corpus.records if r.state in HISTORICAL_STATES]
    other = [r for r in corpus.records if r.state not in STATES]
    lines = [preamble.rstrip(), "", INDEX_MARKER, ""]
    if live:
        lines += ["## Live", ""]
        # State stays visible on live rows: Draft is not binding, and a reader
        # scanning the index should be able to see that it is reading a draft.
        lines += _table(live)
        lines += [""]
    if historical:
        lines += ["## Historical", ""]
        lines += _table(historical)
        lines += [""]
    if other:
        lines += ["## Unclassified", ""]
        lines += _table(other)
        lines += [""]
    if not (live or historical or other):
        lines += ["No records yet.", ""]
    return "\n".join(lines).rstrip() + "\n"


def existing_preamble(directory: Path) -> str:
    """The hand-written part of an existing index, above the marker.

    A file without the marker is refused rather than guessed at: the generator
    cannot tell a reader's prose from its own previous output, and the guess it
    used to make -- treat everything as preamble and append a fresh section --
    silently duplicated the whole index on the next regeneration.
    """
    path = directory / INDEX_NAME
    if not path.exists():
        return DEFAULT_PREAMBLE
    text = path.read_text(encoding="utf-8")
    if INDEX_MARKER not in text:
        raise DrsError(
            f"{path} has no generated-section marker ({INDEX_MARKER}); move anything "
            "you wrote above a line with that marker, or delete the file and regenerate"
        )
    return text.split(INDEX_MARKER, 1)[0].rstrip() + "\n"


def _cells(line: str) -> list[str]:
    """Split one table row into stripped cells, respecting escaped pipes."""
    cells, buf, i = [], [], 0
    while i < len(line):
        ch = line[i]
        if ch == "\\" and i + 1 < len(line) and line[i + 1] == "|":
            buf.append("|")
            i += 2
            continue
        if ch == "|":
            cells.append("".join(buf).strip())
            buf = []
            i += 1
            continue
        buf.append(ch)
        i += 1
    cells.append("".join(buf).strip())
    # A well-formed row starts and ends with a pipe, which yields empty edges.
    return cells[1:-1] if len(cells) > 1 and not cells[0] and not cells[-1] else cells


SECTION_FOR_STATE = {
    "Draft": "Live",
    "Accepted": "Live",
    "Amended": "Live",
    "Deprecated": "Historical",
    "Superseded": "Historical",
}
SECTION_FOR_UNKNOWN_STATE = "Unclassified"


@dataclass
class IndexRow:
    """One row of the index, as a reader finds it."""

    section: str
    id: str
    link: str
    title: str
    summary: str
    state: str
    line: int


def parse_index(text: str, where: str = INDEX_NAME) -> tuple[list[IndexRow], list[Finding]]:
    """Read the index back the way a reader sees it.

    The index is a document a human scans, so a formatter may pad its cells,
    align its separators, reorder nothing, and reflow the preamble above it.
    What this returns is therefore content: every row with the section it sits
    under, in file order, so duplicates stay visible. Comparing bytes would make
    the generator and any formatter permanently wrong about each other; folding
    rows into a dict would make a duplicated row, and a row in the wrong
    section, invisible to the reader and to the audit alike.
    """
    if INDEX_MARKER not in text:
        return [], [
            Finding(
                "error",
                where,
                "index has no generated-section marker; everything below that line "
                "is regenerated, so the generator cannot tell your prose from its own "
                "output (move the prose above the marker, or delete the file and run "
                "`drs.py index`)",
            )
        ]

    rows: list[IndexRow] = []
    findings: list[Finding] = []
    section = ""
    # Report lines as a reader would find them in the file: the generated
    # section starts after the marker, so every offset is relative to it.
    marker_line = text[: text.index(INDEX_MARKER)].count("\n") + 1
    body = text.split(INDEX_MARKER, 1)[1]
    for offset, line in enumerate(body.splitlines(), start=1):
        # The slice starts mid-line, at the marker itself, so offset 1 is the
        # marker's own line.
        lineno = marker_line + offset - 1
        stripped = line.strip()
        if not stripped or stripped == "No records yet.":
            continue
        if stripped.startswith("## "):
            section = stripped[3:].strip()
            continue
        if stripped.startswith("|"):
            cells = _cells(stripped)
            if len(cells) < 3 or cells[0] in ("Record", "") or set(cells[0]) <= {"-", ":"}:
                continue  # header row or separator row
            match = re.match(r"^\[([^\]]+)\]\((.+)\)$", cells[0])
            if not match:
                findings.append(
                    Finding(
                        "error",
                        where,
                        f"index row could not be read (line {lineno}): {stripped[:60]}",
                    )
                )
                continue
            rows.append(
                IndexRow(
                    section=section,
                    id=match.group(1).strip(),
                    link=match.group(2).strip(),
                    title=cells[1],
                    summary=cells[2],
                    state=cells[3] if len(cells) > 3 else "",
                    line=lineno,
                )
            )
            continue
        findings.append(
            Finding(
                "warning",
                where,
                f"line {lineno} sits below the generated marker and will be replaced "
                f"on the next `drs.py index`: {stripped[:60]}",
                kind="lint",
            )
        )
    return rows, findings


def check_index(corpus: Corpus) -> list[Finding]:
    """Compare what the index says about each record, not how it is laid out."""
    path = corpus.directory / INDEX_NAME
    if not path.exists():
        return [Finding("error", INDEX_NAME, "index is missing; run `drs.py index`")]
    rows, out = parse_index(path.read_text(encoding="utf-8"))

    seen: dict[str, int] = {}
    for row in rows:
        if row.id in seen:
            out.append(
                Finding(
                    "error",
                    INDEX_NAME,
                    f"index lists {row.id} more than once (lines {seen[row.id]} and "
                    f"{row.line}); a reader cannot tell which row is current",
                )
            )
            continue
        seen[row.id] = row.line
    listed: dict[str, IndexRow] = {row.id: row for row in rows}

    records = {record.id: record for record in corpus.records if record.id}
    for issue_id in sorted(set(records) - set(listed)):
        out.append(
            Finding("error", INDEX_NAME, f"index is missing {issue_id}; run `drs.py index`")
        )
    for issue_id in sorted(set(listed) - set(records)):
        out.append(
            Finding("error", INDEX_NAME, f"index lists {issue_id}, which is not a record")
        )
    for issue_id in sorted(set(listed) & set(records)):
        row, record = listed[issue_id], records[issue_id]
        fields = (
            ("link", row.link, record.rel.as_posix()),
            ("title", row.title, record.title),
            ("summary", row.summary, record.summary),
            ("state", row.state, record.state),
        )
        wrong = [name for name, got, want in fields if got != want]
        if wrong:
            out.append(
                Finding(
                    "error",
                    INDEX_NAME,
                    f"index is out of date for {issue_id}: {', '.join(wrong)} "
                    "differs; run `drs.py index`",
                )
            )
        want_section = SECTION_FOR_STATE.get(record.state, SECTION_FOR_UNKNOWN_STATE)
        if row.section != want_section:
            out.append(
                Finding(
                    "error",
                    INDEX_NAME,
                    f"index places {issue_id} under {row.section or 'no heading'}, but it is "
                    f"{record.state or 'in no state'}, which belongs under {want_section}",
                )
            )
    return out


def find_records_dir(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit).expanduser().resolve()
    here = Path.cwd().resolve()
    for candidate in (here, *here.parents):
        if (candidate / ".git").exists():
            return candidate / "docs" / "decisions"
    return here / "docs" / "decisions"


def cmd_new(args: argparse.Namespace) -> int:
    directory = find_records_dir(args.dir)
    assets = Path(__file__).resolve().parent.parent / "assets" / "template.md"
    if not assets.exists():
        raise DrsError(f"template not found at {assets}")
    corpus = load(directory) if directory.is_dir() else Corpus(directory=directory)
    numbers = [int(ID_RE.match(r.id).group(1)) for r in corpus.records if ID_RE.match(r.id)]
    number = (max(numbers) + 1) if numbers else 1
    issue_id = canonicalize_id(number)
    slug = re.sub(r"[^a-z0-9]+", "-", args.title.lower()).strip("-")
    if not slug:
        raise DrsError("title has no alphanumerics to build a filename from")
    path = directory / f"{issue_id.split('-', 1)[1]}-{slug}.md"
    if path.exists():
        raise DrsError(f"{path} already exists")

    def quote(value: str) -> str:
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

    def flow(values: list[str]) -> str:
        return ", ".join(quote(value) for value in values)

    authors = args.author or _git_user_name()
    template = assets.read_text(encoding="utf-8")
    text = (
        template.replace("{{id}}", issue_id)
        .replace("{{title}}", args.title.replace("\\", "\\\\").replace('"', '\\"'))
        .replace("{{date}}", datetime.date.today().isoformat())
        .replace("{{authors}}", flow([authors] if authors else []))
        .replace("{{reviewers}}", flow(args.reviewer or []))
    )
    if "{{" in text:
        raise DrsError("template has an unsubstituted placeholder")
    # Parse what we are about to write. A scaffold the tool itself rejects is
    # worse than no scaffold: the failure surfaces after the author has started
    # writing, and looks like their mistake.
    try:
        front_lines, _ = split_document(text, path)
        parse_front_matter(front_lines or [], path)
    except FrontMatterError as exc:
        raise DrsError(f"refusing to write a record that would not parse: {exc}") from exc
    directory.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(path)
    return 0


def _git_user_name() -> str | None:
    try:
        out = subprocess.run(
            ["git", "config", "user.name"], capture_output=True, text=True, check=False
        )
    except OSError:
        return None
    name = out.stdout.strip()
    return name or None


def cmd_index(args: argparse.Namespace) -> int:
    directory = find_records_dir(args.dir)
    corpus = load(directory)
    errors = [f for f in corpus.findings if f.level == "error"]
    text = render_index(corpus, existing_preamble(directory))
    (directory / INDEX_NAME).write_text(text, encoding="utf-8")
    print(f"wrote {directory / INDEX_NAME}")
    if errors:
        print(
            f"drs: {len(errors)} record(s) failed to load and are missing from the index",
            file=sys.stderr,
        )
        return 1
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    directory = find_records_dir(args.dir)
    corpus = load(directory)
    findings = list(corpus.findings)
    for record in corpus.records:
        findings.extend(check_record(record, corpus))
    findings.extend(check_graph(corpus))
    findings.extend(check_index(corpus))

    if args.strict:
        for finding in findings:
            if finding.level == "warning" and finding.kind in STRICT_PROMOTES:
                finding.level = "error"
    errors = [f for f in findings if f.level == "error"]
    warnings = [f for f in findings if f.level == "warning"]
    for finding in errors + warnings:
        stream = sys.stderr if finding.level == "error" else sys.stdout
        print(f"{finding.level}: {finding.where}: {finding.message}", file=stream)
    total = len(corpus.records)
    print(
        f"drs: {total} record(s), {len(errors)} error(s), {len(warnings)} warning(s)",
        file=sys.stderr if errors else sys.stdout,
    )
    return 1 if errors else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="drs.py", description=__doc__.splitlines()[0])
    parser.add_argument("--dir", help="records directory (default: <repo>/docs/decisions)")
    commands = parser.add_subparsers(dest="command", required=True)

    new = commands.add_parser("new", help="scaffold the next record")
    new.add_argument("title")
    new.add_argument("--author", help="author name (default: git config user.name)")
    new.add_argument("--reviewer", action="append", help="reviewer name; repeatable")
    new.set_defaults(func=cmd_new)

    index = commands.add_parser("index", help="regenerate the index")
    index.set_defaults(func=cmd_index)

    check = commands.add_parser("check", help="audit the record set")
    check.add_argument(
        "--strict",
        action="store_true",
        help="fail on tolerated findings too: unmanaged files and junk metadata "
        "(adoption exemptions and duplicate-title warnings stay warnings)",
    )
    check.set_defaults(func=cmd_check)

    # Accept --dir on either side of the subcommand without letting the
    # subparser's default wipe out a value given before it.
    for sub in (new, index, check):
        sub.add_argument("--dir", default=argparse.SUPPRESS, help=argparse.SUPPRESS)

    args = parser.parse_args(argv)
    if not hasattr(args, "dir"):
        args.dir = None
    try:
        return args.func(args)
    except DrsError as exc:
        print(f"drs: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
